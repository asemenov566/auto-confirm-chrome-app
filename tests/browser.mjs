import {createRequire} from 'node:module';
import path from 'node:path';
import {mkdir, cp, readFile, writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const {chromium} = require('playwright');
const runDirectory = path.resolve('tests/profile',String(Date.now()));
const extension = path.join(runDirectory,'extension');
const profile = path.join(runDirectory,'browser');
await mkdir(runDirectory, {recursive:true});
await cp(path.resolve('extension'), extension, {recursive:true, filter: source => path.basename(source) !== 'exceptions.json'});
const fixture = await readFile(new URL('./fixtures/domains.json', import.meta.url), 'utf8');
await writeFile(path.join(extension,'exceptions.json'), fixture);
const launchOptions = {
  channel: process.env.BROWSER_CHANNEL || 'chromium', headless:true,
  args:[`--disable-extensions-except=${extension}`, `--load-extension=${extension}`]
};
let context = await chromium.launchPersistentContext(profile, launchOptions);
try {
  let worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker', {timeout:15000});
  const id = new URL(worker.url()).host;
  const ui = await context.newPage();
  await ui.setViewportSize({width:140,height:46});
  ui.on('pageerror', e => console.log('UI ERROR', e.message));
  ui.on('console', msg => console.log('UI',msg.type(),msg.text()));
  await ui.goto(`chrome-extension://${id}/popup.html`);
  await ui.locator('#enabled').waitFor();
  await ui.waitForFunction(() => !document.querySelector('#enabled').disabled);
  assert.deepEqual(await ui.locator('body').evaluate(e => ({width:e.offsetWidth,height:e.offsetHeight})), {width:140,height:46});
  const developer = ui.locator('footer a');
  assert.equal(await developer.innerText(),'Develop: asemenov566');
  assert.equal(await developer.getAttribute('href'),'https://github.com/asemenov566');
  assert.equal(await developer.getAttribute('target'),'_blank');
  const controlsBottom = await ui.locator('#settings').evaluate(e=>e.getBoundingClientRect().bottom);
  assert.ok((await developer.boundingBox()).y >= controlsBottom);
  const linkBounds = await developer.boundingBox();
  assert.ok(linkBounds.y + linkBounds.height <= 46);
  assert.ok(linkBounds.x >= 0 && linkBounds.x + linkBounds.width <= 140);
  assert.equal(await ui.locator('footer').evaluate(e => getComputedStyle(e).backgroundColor),'rgba(0, 0, 0, 0)');
  const gearBounds = await ui.locator('#settings').boundingBox();
  const arrowBounds = await ui.locator('#settings-tab').boundingBox();
  assert.ok(arrowBounds.x >= gearBounds.x + gearBounds.width);
  assert.ok(arrowBounds.x + arrowBounds.width <= 140);
  const send = msg => ui.evaluate(msg => chrome.runtime.sendMessage(msg), msg);
  const initial = await send({type:'getState'});
  assert.equal(initial.state.domains.length,2);
  await context.route('https://**/*', route => route.fulfill({contentType:'text/html',body:'<!doctype html><title>Local fixture</title><script>window.early=confirm("early")</script>'}));
  await send({type:'setEnabled',enabled:true});
  const site = await context.newPage();
  let dialogs=0;
  site.on('dialog', async d => {dialogs++;await d.dismiss();});
  await site.goto('https://allowed.example/');
  assert.equal(await site.evaluate(() => window.early),true);
  assert.equal(dialogs,0);
  await site.evaluate(() => {window.savedConfirm=window.confirm;});
  await send({type:'setEnabled',enabled:false});
  assert.equal(await site.evaluate(() => window.savedConfirm('cached after OFF')),false);
  assert.equal(await site.evaluate(() => confirm('off')),false);
  assert.equal(dialogs,2);
  await send({type:'setEnabled',enabled:true});
  assert.equal(await site.evaluate(() => confirm('on again')),true);
  await site.goto('https://unlisted.example/');
  assert.equal(await site.evaluate(() => window.early),false);
  assert.equal(dialogs,3);
  await ui.setViewportSize({width:620,height:620});
  await ui.goto(`chrome-extension://${id}/settings.html`);
  assert.equal(await ui.locator('footer a').innerText(),'Develop: asemenov566');
  await ui.waitForFunction(() => !document.querySelector('#domain').disabled);
  await ui.locator('#domain').fill('added.example');
  await ui.locator('#add').click();
  await ui.getByRole('button',{name:'Удалить added.example',exact:true}).waitFor();
  await site.goto('https://added.example/');
  assert.equal(await site.evaluate(() => window.early),true);
  await ui.getByRole('button',{name:'Удалить added.example',exact:true}).click();
  await ui.waitForFunction(() => !document.querySelector('#domain').disabled);
  assert.equal(await site.evaluate(() => confirm('removed')),false);
  await ui.locator('#domain').fill('ПРИМЕР.EXAMPLE');
  await ui.locator('#add').click();
  await ui.getByText('Этот домен уже добавлен.',{exact:true}).waitFor();
  for (const forbidden of ['blocked.example', ' BLOCKED.EXAMPLE. ']) {
    await ui.locator('#domain').fill(forbidden);
    await ui.locator('#add').click();
    await ui.waitForFunction(() => !document.querySelector('#domain').disabled);
    assert.equal(await ui.locator('#domain').inputValue(), '');
    assert.equal(await ui.locator('#status').innerText(), '');
    assert.equal(await ui.locator('#domain').getAttribute('aria-invalid'), null);
    assert.equal(await ui.getByRole('button',{name:'Удалить blocked.example',exact:true}).count(),0);
    const rejected = await send({type:'getState'});
    assert.ok(!rejected.state.domains.some(d => d.host === 'blocked.example'));
  }
  const directRejected = await send({type:'addDomain',domain:'blocked.example'});
  assert.equal(directRejected.ok,true);
  assert.equal(directRejected.ignored,true);
  assert.ok(!directRejected.state.domains.some(d => d.host === 'blocked.example'));
  await site.goto('https://пример.example/');
  assert.equal(await site.evaluate(() => window.early),true);
  await ui.screenshot({path:'tests/settings.png',fullPage:true});
  await ui.setViewportSize({width:140,height:46});
  await ui.goto(`chrome-extension://${id}/popup.html`);
  await ui.waitForFunction(() => !document.querySelector('#enabled').disabled);
  assert.equal(await ui.locator('#enabled').isChecked(),true);
  await ui.screenshot({path:'tests/popup.png',clip:{x:0,y:0,width:140,height:46}});
  const win = await send({type:'openSettings'});
  assert.equal(win.ok,true);
  const windows = await worker.evaluate(() => chrome.windows.getAll());
  assert.ok(windows.some(w => w.type === 'popup'));
  const tabLauncher = await context.newPage();
  await tabLauncher.goto(`chrome-extension://${id}/popup.html`);
  await tabLauncher.waitForFunction(() => !document.querySelector('#enabled').disabled);
  const newTabPromise = context.waitForEvent('page');
  await tabLauncher.locator('#settings-tab').click();
  const settingsTab = await newTabPromise;
  await settingsTab.waitForURL(`chrome-extension://${id}/settings.html`);
  await settingsTab.waitForFunction(() => !document.querySelector('#domain').disabled);
  assert.equal(await settingsTab.evaluate(async () => (await chrome.windows.getCurrent()).type),'normal');
  assert.equal(await settingsTab.locator('footer a').innerText(),'Develop: asemenov566');
  assert.match(await settingsTab.locator('header p').innerText(),/Когда приложение выключено, оно ничего не делает/);
  const afterTab = await worker.evaluate(() => chrome.windows.getAll());
  assert.equal(afterTab.filter(w=>w.type==='popup').length,windows.filter(w=>w.type==='popup').length);
  await settingsTab.locator('#domain').fill('from-tab.example');
  await settingsTab.locator('#add').click();
  await settingsTab.getByRole('button',{name:'Удалить from-tab.example',exact:true}).waitFor();
  assert.ok((await send({type:'getState'})).state.domains.some(d=>d.host==='from-tab.example'));
  await send({type:'addDomain',domain:'persist.example'});
  await context.close();
  context = await chromium.launchPersistentContext(profile, launchOptions);
  const restored = await context.newPage();
  await restored.goto(`chrome-extension://${id}/popup.html`);
  await restored.waitForFunction(() => !document.querySelector('#enabled').disabled);
  assert.equal(await restored.locator('#enabled').isChecked(),true);
  const restoredState = await restored.evaluate(() => chrome.runtime.sendMessage({type:'getState'}));
  assert.ok(restoredState.state.domains.some(d => d.host === 'persist.example'));
  await restored.evaluate(() => chrome.runtime.sendMessage({type:'setEnabled',enabled:false}));
  console.log('PASS: silent blocked.example rejection, cleared field, no error or success message, normalized variants, worker-side enforcement; existing extension scenarios and browser restart persistence.');
} finally {await context.close();}
